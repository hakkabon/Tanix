/// Glyph bitmap for an ASCII character, if the font covers it.
pub fn glyph(c: u8) -> Option<&'static [u8; GLYPH_H]> {
    match c {
        b'A'..=b'Z' => Some(&FONT[(c - b'A') as usize]),
        b'0'..=b'9' => Some(&FONT[26 + (c - b'0') as usize]),
        b'.' => Some(&FONT[36]),
        b'-' => Some(&FONT[37]),
        b'+' => Some(&FONT[38]),
        b':' => Some(&FONT[39]),
        b'!' => Some(&FONT[40]),
        _ => None,
    }
}

/// Draw one glyph into a BGRA8888 buffer.  `x`/`y` are the top-left corner
/// of the glyph's cell; `scale` multiplies each font pixel.  Returns the
/// horizontal advance (0 for unknown characters, so callers can skip).
pub fn draw_char(fb: &mut [u8], stride: usize, x: i32, y: i32, scale: u32, rgb: (u8, u8, u8), c: u8) -> usize {
    let Some(g) = glyph(c) else {
        return 0;
    };
    let (r, g8, b) = rgb;
    for (row, bits) in g.iter().enumerate() {
        for col in 0..GLYPH_W {
            if bits & (1 << (4 - col)) == 0 {
                continue;
            }
            let px = x + (col as i32) * scale as i32;
            let py = y + (row as i32) * scale as i32;
            for sy in 0..scale as i32 {
                for sx in 0..scale as i32 {
                    let (dx, dy) = (px + sx, py + sy);
                    if dx < 0 || dy < 0 {
                        continue;
                    }
                    let off = dy as usize * stride + dx as usize * 4;
                    if off + 3 >= fb.len() {
                        continue;
                    }
                    fb[off] = b;
                    fb[off + 1] = g8;
                    fb[off + 2] = r;
                    fb[off + 3] = 0xFF;
                }
            }
        }
    }
    GLYPH_ADV * scale as usize
}

/// Draw a string into a BGRA8888 buffer; returns the total advance.
pub fn draw_str(fb: &mut [u8], stride: usize, x: i32, y: i32, scale: u32, rgb: (u8, u8, u8), s: &str) -> usize {
    let mut adv = 0usize;
    for &c in s.as_bytes() {
        let a = draw_char(fb, stride, x + adv as i32, y, scale, rgb, c);
        adv += if a == 0 { GLYPH_ADV * scale as usize } else { a };
    }
    adv
}

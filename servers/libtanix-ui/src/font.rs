//! Tiny 5×7 bitmap font (Phase 8).
//!
//! Shared by the display server (window title bars) and the demo apps
//! (counter digits, button glyphs).  Glyphs are 5 columns × 7 rows, one
//! byte per row, bit 4 (MSB) = leftmost column.  Covers A-Z, 0-9 and a few
//! punctuation marks; unknown characters render as an empty advance.

/// Glyph width in pixels.
pub const GLYPH_W: usize = 5;
/// Glyph height in pixels.
pub const GLYPH_H: usize = 7;
/// Advance width per character (glyph width + one column of spacing).
pub const GLYPH_ADV: usize = 6;

